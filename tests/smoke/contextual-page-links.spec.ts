import { expect, type Locator, type Page, test } from '@playwright/test'
import { LocalTemplatesFixture, NOTES } from './localTemplatesFixture'
import { triggerMenuCommand } from './testBridge'

let fixture: LocalTemplatesFixture
const pane = (page: Page, number: number) => page.locator(`section[aria-label="Page pane ${number}"]`)
const rich = (owner: Locator) => owner.locator('.bn-editor')
const menu = (page: Page) => page.locator('.wikilink-menu')
const raw = (owner: Locator) => owner.getByTestId('raw-editor-codemirror')
const STRUCTURED = '# Structured writing\n\n- [ ] Review the harbor\n\n| Topic | Detail |\n| --- | --- |\n| Plan | Keep this cell |\n\nContinue writing here.\n'

async function openPage(page: Page, title: string, path: string, number = 1) {
  await page.getByTestId('sidebar-top-nav').getByRole('button', { name: 'Search', exact: true }).click()
  const finder = page.getByRole('dialog', { name: 'Find a page' })
  await finder.getByRole('combobox').fill(title)
  await finder.getByRole('group', { name: 'Pages', exact: true }).getByRole('option')
    .filter({ hasText: new RegExp(`^${title}`) }).first().click()
  await expect(finder).toBeHidden()
  await expect(pane(page, number)).toHaveAttribute('data-note-path', fixture.file(path))
}

async function splitGarden(page: Page) {
  await page.getByRole('button', { name: 'Split right', exact: true }).click()
  await pane(page, 2).getByText('Open a page here').click()
  await openPage(page, 'Garden note', 'garden-note.md', 2)
}

async function startLink(page: Page, paragraph: Locator, query = '') {
  await paragraph.click()
  await page.keyboard.press('End')
  await page.keyboard.type(` [[${query}`)
  await expect(menu(page)).toBeVisible()
}

async function save(page: Page) { await triggerMenuCommand(page, 'file-save') }
async function toRaw(owner: Locator) {
  await owner.getByRole('button', { name: 'Open the raw editor', exact: true }).click()
  await expect(raw(owner)).toBeVisible()
}
async function toRich(owner: Locator) {
  await owner.getByRole('button', { name: 'Return to the editor', exact: true }).click()
  await expect(rich(owner)).toBeVisible()
}

test.use({ viewport: { width: 1600, height: 1000 } })
test.describe.configure({ retries: 0, timeout: 60_000 })
test.beforeEach(async ({ page }) => {
  fixture = new LocalTemplatesFixture(page, false)
  fixture.write('recent-note.md', '# Recent note\n\nA page visited earlier.\n')
  fixture.write('work/shared/plan.md', '# Plan\n\nThe work plan stays here.\n')
  fixture.write('home/shared/plan.md', '# Plan\n\nThe home plan stays here.\n')
  fixture.write('structured.md', STRUCTURED)
  await fixture.open()
})
test.afterEach(async () => { await fixture?.dispose() })

test('empty discovery prefers the other pane and real recents; mouse and Enter insert once into their owner', async ({ page }) => {
  await openPage(page, 'Recent note', 'recent-note.md')
  await openPage(page, 'Harbor note', 'harbor-note.md')
  await splitGarden(page)
  const left = pane(page, 1)
  const right = pane(page, 2)
  // Visit a newer page in the left pane after opening Garden: visible context must
  // outrank recency, rather than merely matching its accidental current order.
  await rich(left).getByText('The harbor lantern is ready.', { exact: true }).click()
  await openPage(page, 'Recent note', 'recent-note.md')
  await openPage(page, 'Harbor note', 'harbor-note.md')
  const originalRight = fixture.read('garden-note.md')
  const leftEditor = await rich(left).elementHandle()
  await startLink(page, rich(left).getByText('The harbor lantern is ready.', { exact: true }))
  await expect(menu(page).getByRole('button').nth(0)).toHaveText('Garden note')
  await expect(menu(page).getByRole('button').nth(1)).toHaveText('Recent note')
  await menu(page).getByRole('button', { name: 'Garden note', exact: true }).click()
  await expect(menu(page)).toBeHidden()
  await expect(rich(left).locator('.wikilink[data-target="garden-note"]')).toHaveCount(1)
  await page.keyboard.type(' Mouse selection stays here.')
  await save(page)
  await expect.poll(() => fixture.read('harbor-note.md')).toContain('Mouse selection stays here.')
  expect(fixture.read('garden-note.md')).toBe(originalRight)
  expect(await leftEditor?.evaluate(element => element.isConnected)).toBe(true)

  await startLink(page, rich(right).getByText('The pear tree is in bloom.', { exact: true }))
  await expect(menu(page).getByRole('button').first()).toHaveText('Harbor note')
  await page.keyboard.press('Enter')
  await expect(rich(right).locator('.wikilink[data-target="harbor-note"]')).toHaveCount(1)
  await page.keyboard.type(' Keyboard selection stays here.')
  await save(page)
  await expect.poll(() => fixture.read('garden-note.md')).toContain('Keyboard selection stays here.')
  expect(fixture.read('harbor-note.md').match(/\[\[garden-note\]\]/g)).toHaveLength(1)

  await right.getByRole('button', { name: 'Close pane', exact: true }).click()
  await openPage(page, 'Recent note', 'recent-note.md')
  await openPage(page, 'Harbor note', 'harbor-note.md')
  await startLink(page, rich(pane(page, 1)).locator('p').last())
  await expect(menu(page).getByRole('button').first()).toHaveText('Recent note')
  await page.keyboard.press('Escape')
  expect(fixture.remoteRequests).toEqual([])
})

test('nested duplicate titles have distinct folder cues and persist the exact selected destination', async ({ page }) => {
  await openPage(page, 'Harbor note', 'harbor-note.md')
  await startLink(page, rich(pane(page, 1)).getByText('The harbor lantern is ready.', { exact: true }), 'Plan')
  const work = menu(page).getByRole('button').filter({ hasText: 'work/shared' })
  const home = menu(page).getByRole('button').filter({ hasText: 'home/shared' })
  await expect(work).toHaveCount(1)
  await expect(home).toHaveCount(1)
  await expect(menu(page)).not.toContainText(fixture.vault)
  await work.click()
  const link = rich(pane(page, 1)).locator('.wikilink[data-target="work/shared/plan"]')
  await expect(link).toHaveCount(1)
  await save(page)
  await expect.poll(() => fixture.read('harbor-note.md')).toContain('[[work/shared/plan]]')
  await toRaw(pane(page, 1))
  await expect(raw(pane(page, 1))).toContainText('[[work/shared/plan]]')
  await toRich(pane(page, 1))
  await link.click({ modifiers: ['Meta'] })
  await expect(pane(page, 1)).toHaveAttribute('data-note-path', fixture.file('work/shared/plan.md'))
  await expect(rich(pane(page, 1))).toContainText('The work plan stays here.')
  expect(fixture.read('home/shared/plan.md')).toBe('# Plan\n\nThe home plan stays here.\n')
})

test('Escape and search dismiss suggestions without inserting into another pane or stealing its typing', async ({ page }) => {
  await openPage(page, 'Harbor note', 'harbor-note.md')
  await splitGarden(page)
  await startLink(page, rich(pane(page, 1)).getByText('The harbor lantern is ready.', { exact: true }), 'Plan')
  await page.keyboard.press('Escape')
  await expect(menu(page)).toBeHidden()
  await rich(pane(page, 2)).getByText('The pear tree is in bloom.', { exact: true }).click()
  await page.keyboard.press('End')
  await page.keyboard.type(' Keep writing in the garden.')
  await save(page)
  await expect.poll(() => fixture.read('garden-note.md')).toContain('Keep writing in the garden.')
  expect(fixture.read('garden-note.md')).not.toContain('[[')
  await startLink(page, rich(pane(page, 1)).locator('p').last(), 'Plan')
  await openPage(page, 'Recent note', 'recent-note.md')
  await expect(menu(page)).toBeHidden()
  await rich(pane(page, 1)).getByText('A page visited earlier.', { exact: true }).click()
  await page.keyboard.press('End')
  await page.keyboard.type(' A clean continuation.')
  await save(page)
  await expect.poll(() => fixture.read('recent-note.md')).toContain('A clean continuation.')
  expect(fixture.read('recent-note.md')).not.toContain('[[')
  await expect(rich(pane(page, 2))).toContainText('Keep writing in the garden.')
})

test('checklist and table links survive mode round trips, neighboring edits and local reopen', async ({ page }) => {
  await openPage(page, 'Structured writing', 'structured.md')
  await splitGarden(page)
  const owner = pane(page, 1)
  const check = rich(owner).locator('[data-content-type="checkListItem"]')
  await startLink(page, check.getByText('Review the harbor', { exact: true }), 'Harbor note')
  await menu(page).getByRole('button', { name: 'Harbor note', exact: true }).click()
  await check.locator('input[type="checkbox"]').check()
  const cell = rich(owner).locator('td').first()
  await startLink(page, cell, 'Garden note')
  await page.keyboard.press('Enter')
  await rich(owner).locator('td').nth(1).click()
  await page.keyboard.press('End')
  await page.keyboard.type(' Intact neighbor.')
  await save(page)
  await expect.poll(() => fixture.read('structured.md')).toContain('[[garden-note]]')
  await toRaw(owner)
  await expect(raw(owner)).toContainText('- [x] Review the harbor [[harbor-note]]')
  await expect(raw(owner)).toContainText('Intact neighbor.')
  await toRich(owner)
  await expect(check.locator('input[type="checkbox"]')).toBeChecked()
  await expect(rich(owner).locator('table .wikilink[data-target="garden-note"]')).toHaveCount(1)
  await openPage(page, 'Recent note', 'recent-note.md')
  await openPage(page, 'Structured writing', 'structured.md')
  await expect(check.locator('input[type="checkbox"]')).toBeChecked()
  await expect(rich(owner).locator('table')).toContainText('Intact neighbor.')
  expect(fixture.read('garden-note.md')).toBe(NOTES['garden-note.md'])
})

test('structured Markdown and a URL over selected text preserve content through save and reopen', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await openPage(page, 'Harbor note', 'harbor-note.md')
  const owner = pane(page, 1)
  await rich(owner).getByText('The harbor lantern is ready.', { exact: true }).click()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await page.evaluate(text => navigator.clipboard.writeText(text), '## Pasted outline\n\n- [x] Already done\n- [ ] A gentle next step\n')
  await page.keyboard.press('ControlOrMeta+V')
  await expect(rich(owner)).toContainText('Pasted outline')
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await page.keyboard.type('Harbor reference')
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+Shift+ArrowLeft' : 'Control+Shift+ArrowLeft')
  await page.evaluate(text => navigator.clipboard.writeText(text), 'https://example.com/local-reference')
  await page.keyboard.press('ControlOrMeta+V')
  await expect(rich(owner).locator('a[href="https://example.com/local-reference"]')).toHaveText('Harbor reference')
  await save(page)
  await expect.poll(() => fixture.read('harbor-note.md')).toContain('[Harbor reference](https://example.com/local-reference)')
  await openPage(page, 'Garden note', 'garden-note.md')
  await openPage(page, 'Harbor note', 'harbor-note.md')
  await expect(rich(owner)).toContainText('Pasted outline')
  await expect(rich(owner).locator('input[type="checkbox"]').first()).toBeChecked()
  await expect(rich(owner).locator('a[href="https://example.com/local-reference"]')).toHaveText('Harbor reference')
  expect(fixture.remoteRequests).toEqual([])
})
